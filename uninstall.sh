#!/bin/bash
# Removes Foldlet groups from your Dock and trashes only verified group bundles
# and their matching data files. Unrelated files and symbolic links are preserved.
#
#   curl -fsSL https://raw.githubusercontent.com/wmtaff/foldlet/main/uninstall.sh | bash
set -euo pipefail

GROUPS_DIR="$HOME/Applications/Foldlet"
DATA_DIR="$HOME/Library/Application Support/Foldlet"
TRASH_DIR="$HOME/.Trash"

# Never traverse a redirected installation or data directory during cleanup.
for d in "$GROUPS_DIR" "$DATA_DIR" "$TRASH_DIR"; do
  if [ -L "$d" ]; then
    echo "Cannot safely uninstall through a symbolic link: $d" >&2
    exit 1
  fi
done

shopt -s nullglob
apps=()
ids=()
for app in "$GROUPS_DIR"/*.app; do
  [ -d "$app" ] && [ ! -L "$app" ] || continue
  [ -d "$app/Contents" ] && [ ! -L "$app/Contents" ] || continue
  plist="$app/Contents/Info.plist"
  [ -f "$plist" ] && [ ! -L "$plist" ] || continue
  marker=$(/usr/libexec/PlistBuddy -x -c 'Print :FoldletGroup' "$plist" 2>/dev/null) || continue
  bid=$(/usr/libexec/PlistBuddy -c 'Print :CFBundleIdentifier' "$plist" 2>/dev/null) || continue
  exe=$(/usr/libexec/PlistBuddy -c 'Print :CFBundleExecutable' "$plist" 2>/dev/null) || continue
  # These are the identifiers generated by install.sh and Groups.newBundleID().
  [[ "$marker" == *'<true/>'* ]] && [ "$exe" = "Foldlet" ] || continue
  [[ "$bid" =~ ^io\.github\.wmtaff\.foldlet\.group\.[0-9a-f]{8}$ ]] || continue
  apps+=("$app")
  ids+=("$bid")
done

if [ ${#apps[@]} -gt 0 ]; then
  # Unique destinations avoid merging app bundles and data directories in Trash.
  mkdir -p "$TRASH_DIR"
  destination=$(mktemp -d "$TRASH_DIR/Foldlet-uninstall-XXXXXX")
  mkdir "$destination/Groups" "$destination/Data"

  echo "→ Removing Foldlet groups from the Dock…"
  cleaned_dock=false
  for app in "${apps[@]}"; do
    executable="$app/Contents/MacOS/Foldlet"
    [ -d "$app/Contents/MacOS" ] && [ ! -L "$app/Contents/MacOS" ] || continue
    [ -f "$executable" ] && [ -x "$executable" ] && [ ! -L "$executable" ] || continue
    if "$executable" --remove-all-from-dock; then
      cleaned_dock=true
      break
    fi
  done
  if [ "$cleaned_dock" = false ]; then
    echo "Couldn't remove Dock icons automatically; remove any remaining Foldlet icons manually." >&2
  fi
  killall Foldlet 2>/dev/null || true

  for i in "${!apps[@]}"; do
    app="${apps[$i]}"
    mv "$app" "$destination/Groups/"
    echo "→ Moved $app to the Trash"
    data="$DATA_DIR/${ids[$i]}.json"
    if [ -f "$data" ] && [ ! -L "$data" ]; then
      mv "$data" "$destination/Data/"
      echo "→ Moved $data to the Trash"
    fi
  done
else
  echo "No verified Foldlet groups found."
fi

# Remove only empty containers. Unknown files, orphaned data and symlinks stay put.
for d in "$GROUPS_DIR" "$DATA_DIR"; do
  rmdir "$d" 2>/dev/null || true
  if [ -e "$d" ]; then
    echo "→ Preserved remaining contents in $d"
  fi
done

echo "✓ Foldlet cleanup finished."
